-- 创建主播表
create table public.streamers (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null unique,
  color text default '#667eea'
);

-- 启用 Row Level Security (RLS)
alter table public.streamers enable row level security;

-- 创建策略：允许所有用户操作主播表
create policy "Allow public access to streamers"
on public.streamers
for all
using (true)
with check (true);

-- 创建工作记录表
create table public.work_records (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  streamer_id bigint references public.streamers(id) on delete cascade,
  start_time timestamp with time zone not null,
  end_time timestamp with time zone not null,
  total_hours numeric not null,
  total_salary numeric not null,
  note text
);

-- 启用 Row Level Security (RLS)
alter table public.work_records enable row level security;

-- 创建策略：允许所有用户操作工作记录表
create policy "Allow public access to work_records"
on public.work_records
for all
using (true)
with check (true);
